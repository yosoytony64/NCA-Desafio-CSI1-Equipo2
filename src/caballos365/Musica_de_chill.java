    private void PausarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_PausarActionPerformed
        if (mediaPlayer != null) {
            if (mediaPlayer.getStatus() == javafx.scene.media.MediaPlayer.Status.PLAYING) {
                mediaPlayer.pause();
                timer.stop();
            } else {
                mediaPlayer.play();
                timer.start();
            }
        }
    }// GEN-LAST:event_PausarActionPerformed

    private void StopActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_StopActionPerformed
        if (mediaPlayer != null) {
            mediaPlayer.stop();
            timer.stop();
            jSlider1.setValue(0);
        }
    }// GEN-LAST:event_StopActionPerformed

    private void jSlider1MouseDragged(java.awt.event.MouseEvent evt) {// GEN-FIRST:event_jSlider1MouseDragged
        if (mediaPlayer != null) {
            Duration duration_segundos = Duration.seconds(jSlider1.getValue());
            mediaPlayer.seek(duration_segundos);
        }
    }// GEN-LAST:event_jSlider1MouseDragged

    // Timer para sincronizar el slider con el progreso real del mediaPlayer
    Timer timer = new Timer(500, new ActionListener() {
        public void actionPerformed(java.awt.event.ActionEvent e) {
            if (mediaPlayer != null && mediaPlayer.getStatus() == javafx.scene.media.MediaPlayer.Status.PLAYING) {
                jSlider1.setValue((int) mediaPlayer.getCurrentTime().toSeconds());
            }
        }
    });

