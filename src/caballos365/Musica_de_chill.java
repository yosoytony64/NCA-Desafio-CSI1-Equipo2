    /**
     * Método para reproducir la canción seleccionada en la lista.
     */
    public void reproducirMusica() {
        // Detener reproducción previa si existe
        if (mediaPlayer != null) {
            mediaPlayer.stop();
            mediaPlayer.dispose();
        }

        String selected = lista.getSelectedValue();
        if (selected == null || selected.trim().isEmpty()) {
            return;
        }

        try {
            String path = selected + ".mp3";
            File file = new File(path);
            if (file.exists()) {
                Media media = new Media(file.toURI().toString());
                mediaPlayer = new javafx.scene.media.MediaPlayer(media);
                
                // Al estar listo, configuramos el slider
                mediaPlayer.setOnReady(() -> {
                    jSlider1.setMaximum((int) mediaPlayer.getTotalDuration().toSeconds());
                    jSlider1.setValue(0);
                });

                mediaPlayer.play();
                timer.start();
            } else {
                System.err.println("Archivo no encontrado: " + path);
            }
        } catch (Exception e) {
            System.err.println("Error al reproducir: " + e.getMessage());
        }
    }

    /**
     * Método para pasar a la siguiente canción de la lista.
     */
    public void siguienteCancion() {
        int index = lista.getSelectedIndex();
        int size = lista.getModel().getSize();

        // Incrementamos el índice (si llegamos al final, volvemos al principio)
        int nextIndex = (index + 1) % size;
        
        // Evitamos bucles infinitos si la lista está vacía o solo tiene espacios en blanco
        if (size > 0) {
            lista.setSelectedIndex(nextIndex);
            reproducirMusica();
        }
    }

