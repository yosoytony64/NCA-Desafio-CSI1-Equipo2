public class Ongs {
    private int id_ong;
    private String nombre;
    private String area;
    private String donacion_total;

    /**
     * @return the id_ong
     */
    public int getId_ong() {
        return id_ong;
    }

    /**
     * @param id_ong the id_ong to set
     */
    public void setId_ong(int id_ong) {
        this.id_ong = id_ong;
    }

    /**
     * @return the nombre
     */
    public String getNombre() {
        return nombre;
    }

    /**
     * @param nombre the nombre to set
     */
    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    /**
     * @return the area
     */
    public String getArea() {
        return area;
    }

    /**
     * @param area the area to set
     */
    public void setArea(String area) {
        this.area = area;
    }

    /**
     * @return the donacion_total
     */
    public String getDonacion_total() {
        return donacion_total;
    }

    /**
     * @param donacion_total the donacion_total to set
     */
    public void setDonacion_total(String donacion_total) {
        this.donacion_total = donacion_total;
    }
}
